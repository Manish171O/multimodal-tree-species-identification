"""Turn the experiment summary into results.md tables and comparison plots."""
from __future__ import annotations

from pathlib import Path
from typing import Any

import numpy as np

from src.evaluation import plots as P

SINGLE_DROPS = ("drop_rgb", "drop_hsi", "drop_lidar")
SCEN_ORDER = ("all_sensors", "drop_rgb", "drop_hsi", "drop_lidar", "lidar_only", "hsi_only", "rgb_only")


def run_row(r: dict[str, Any]) -> dict[str, float]:
    """Headline numbers of one run (test sites unless prefixed val_)."""
    te, va = r["test"]["scenarios"], r["val"]["scenarios"]
    a, s = te["all_sensors"]["all"], te["all_sensors"]["seen_species"]
    return {
        "val_macro_f1": va["all_sensors"]["all"]["macro_f1"],
        "test_acc": a["accuracy"], "test_macro_f1": a["macro_f1"], "test_weighted_f1": a["weighted_f1"],
        "test_ece": a["ece"], "seen_acc": s["accuracy"], "seen_macro_f1": s["macro_f1"],
        "one_missing_acc": float(np.mean([te[k]["all"]["accuracy"] for k in SINGLE_DROPS])),
        "one_missing_macro_f1": float(np.mean([te[k]["all"]["macro_f1"] for k in SINGLE_DROPS])),
        "hsi_drop_effect": te["drop_hsi"]["all"]["accuracy"] - a["accuracy"],
    }


def _fmt_table(rows: list[tuple[str, dict[str, float]]], ref: dict[str, float] | None = None) -> str:
    cols = [("val_macro_f1", "val mF1"), ("test_acc", "test acc"), ("test_macro_f1", "test mF1"),
            ("test_weighted_f1", "test wF1"), ("test_ece", "ECE ↓"), ("seen_acc", "acc (seen sp.)"),
            ("seen_macro_f1", "mF1 (seen sp.)"), ("one_missing_acc", "acc, 1 sensor missing"),
            ("one_missing_macro_f1", "mF1, 1 sensor missing")]
    head = "| run | " + " | ".join(c[1] for c in cols) + " |"
    sep = "|---|" + "---|" * len(cols)
    lines = [head, sep]
    for name, row in rows:
        cells = []
        for k, _ in cols:
            v = f"{row[k]:.3f}"
            if ref is not None and name != "(final)":
                d = row[k] - ref[k]
                v += f" ({d:+.3f})"
            cells.append(v)
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def write_report(summary: dict[str, Any], out: Path) -> str:
    """Write results.md and plots; return the markdown."""
    runs = summary["runs"]
    sel = summary["selected_variant"]
    rows = {n: run_row(r) for n, r in runs.items()}
    variants = [n for n in runs if "__" not in n]
    ablations = [n for n in runs if n.startswith(sel + "__") and "__seed" not in n]
    seed_runs = [n for n in runs if "__seed" in n]
    md: list[str] = ["# Results — Adaptive Quality-Aware Multimodal Tree Species Identification", ""]
    if runs[sel]["test"].get("synthetic_data"):
        md += ["> **All numbers are on SYNTHETIC demo data** (NEON-MMTC-like layout, generated by "
               "`src/data/synthetic.py`). They show that the pipeline works and how the components "
               "interact. They are **not** estimates of real-world accuracy.", ""]
    if summary.get("quick"):
        md += ["> `--quick` run (3 epochs, 256 training crowns): pipeline check only.", ""]
    t = runs[sel]["test"]
    md += [f"Site-held-out evaluation. Test sites: {', '.join(t['sites'])} (n = {t['n_samples']}). "
           f"Final model chosen on **validation** macro-F1: **`{sel}`**. Single seed (42).", ""]

    md += ["## 1. Variants (cross-site robustness fix)", "",
           _fmt_table([(n, rows[n]) for n in variants]), "",
           "`acc/mF1, 1 sensor missing` = mean over drop-RGB, drop-HSI and drop-LiDAR.", ""]
    if ablations:
        md += [f"## 2. Ablations (on top of `{sel}`; Δ vs final model)", "",
               _fmt_table([("(final)", rows[sel])] + [(n.split("__", 1)[1], rows[n]) for n in ablations], rows[sel]),
               ""]
    md += [f"## 3. Missing-sensor robustness — test accuracy (macro-F1)", "",
           "| run | " + " | ".join(s.replace("_", " ") for s in SCEN_ORDER) + " |",
           "|---|" + "---|" * len(SCEN_ORDER)]
    for n in variants + ablations:
        sc = runs[n]["test"]["scenarios"]
        md.append(f"| {n.split('__')[-1]} | " + " | ".join(
            f"{sc[s]['all']['accuracy']:.3f} ({sc[s]['all']['macro_f1']:.3f})" for s in SCEN_ORDER) + " |")
    md.append("")
    if all("corruptions" in runs[n]["test"] for n in variants + ablations):
        cn = list(runs[sel]["test"]["corruptions"])
        md += ["## 3b. Silent sensor corruption at test time — test accuracy (macro-F1)", "",
               "A sensor is still *present*, but its input is corrupted. These corruptions were never seen in "
               "training: Gaussian noise of 2σ on RGB or HSI; LiDAR xyz jitter of 1σ with 80 % of points removed. "
               "This is where per-sample trust should matter most.", "",
               "| run | clean | " + " | ".join(c.replace("_", " ") for c in cn) + " | mean over corruptions |",
               "|---|---|" + "---|" * (len(cn) + 1)]
        for n in variants + ablations:
            t_ = runs[n]["test"]
            vals = [t_["corruptions"][c]["all"] for c in cn]
            md.append(f"| {n.split('__')[-1]} | {t_['scenarios']['all_sensors']['all']['accuracy']:.3f} | "
                      + " | ".join(f"{v['accuracy']:.3f} ({v['macro_f1']:.3f})" for v in vals)
                      + f" | {np.mean([v['accuracy'] for v in vals]):.3f} |")
        md.append("")
        md += ["Fusion weight given to the corrupted sensor (final model vs no quality estimator):", "",
               "| run | " + " | ".join(cn) + " |", "|---|" + "---|" * len(cn)]
        for n in [sel] + [a for a in ablations if a.endswith("no_quality_estimator")]:
            w = runs[n]["test"]["corruptions"]
            md.append(f"| {n.split('__')[-1]} | " + " | ".join(
                f"{w[c]['mean_fusion_weight'][c.split('_')[0]]:.3f}" for c in cn) + " |")
        md.append("")
    if seed_runs:
        md += _seed_section(runs, rows, sel, seed_runs)
    tr = runs[sel]["test"].get("trust_vs_degradation_synthetic_truth")
    if tr:
        md += [f"## 4. Does trust track sensor quality? (`{sel}`, test sites, synthetic ground truth)", "",
               "| sensor | trust clean | trust degraded | fusion weight clean | fusion weight degraded | AUROC (degraded detection) | n degraded |",
               "|---|---|---|---|---|---|---|"]
        for m, v in tr.items():
            md.append(f"| {m} | {v['trust_clean']:.3f} | {v['trust_degraded']:.3f} | {v['weight_clean']:.3f} | "
                      f"{v['weight_degraded']:.3f} | {v.get('auroc_degraded_detection', float('nan')):.3f} | {v['n_degraded']} |")
        md.append("")
    st = runs[sel]["test"]["structure"]
    md += [f"## 5. Auxiliary structure head (`{sel}`, test)", "",
           f"Height: MAE {st['height_m']['mae']:.2f} m, RMSE {st['height_m']['rmse']:.2f} m, R² {st['height_m']['r2']:.3f}. "
           f"Crown diameter: MAE {st['crown_diameter_m']['mae']:.2f} m, R² {st['crown_diameter_m']['r2']:.3f}.", ""]
    md += ["## Plots", "", "- `plots/comparison.png`: test accuracy and macro-F1 for every run",
           "- `plots/missing_sensors.png`: accuracy under missing sensors, final vs ablations",
           "- `plots/corrupted_sensors.png`: accuracy under silent test-time corruption, final vs ablations",
           f"- `{sel}/eval_test/plots/`: confusion matrix, reliability diagram, per-species F1, trust weights", ""]
    text = "\n".join(md)
    (out / "results.md").write_text(text, encoding="utf-8")
    (out / "plots").mkdir(exist_ok=True)
    _plot_comparison(rows, variants + ablations, sel, out / "plots" / "comparison.png")
    _plot_missing(runs, [sel] + ablations, out / "plots" / "missing_sensors.png")
    if all("corruptions" in runs[n]["test"] for n in [sel] + ablations):
        _plot_missing(runs, [sel] + ablations, out / "plots" / "corrupted_sensors.png", corrupt=True)
    return text


def _short(n: str) -> str:
    return n.split("__")[-1].replace("_", " ")


def _plot_comparison(rows: dict[str, dict[str, float]], names: list[str], sel: str, path: Path) -> None:
    plt = P.plt
    y = np.arange(len(names))[::-1]
    h = 0.36
    fig, ax = plt.subplots(figsize=(7.5, 0.55 * len(names) + 1.6))
    acc = [rows[n]["test_acc"] for n in names]
    f1 = [rows[n]["test_macro_f1"] for n in names]
    ax.barh(y + h / 2, acc, h * 0.92, color=P.S1, label="Test accuracy")
    ax.barh(y - h / 2, f1, h * 0.92, color=P.S2, label="Test macro-F1")
    for yi, a, f in zip(y, acc, f1):
        ax.text(a + 0.01, yi + h / 2, f"{a:.3f}", va="center", color=P.INK2, fontsize=8)
        ax.text(f + 0.01, yi - h / 2, f"{f:.3f}", va="center", color=P.INK2, fontsize=8)
    ax.set_yticks(y, [_short(n) + ("  (final)" if n == sel else "") for n in names])
    ax.set_xlim(0, 1)
    ax.grid(axis="y", visible=False)
    ax.set_xlabel("Score on held-out test sites")
    ax.set_title("Variants and ablations")
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.12 - 0.3 / len(names)), ncol=2)
    P._save(fig, path)


def _plot_missing(runs: dict[str, Any], names: list[str], path: Path, corrupt: bool = False) -> None:
    """Grouped bars of test accuracy per scenario (missing sensors, or silent corruptions)."""
    plt = P.plt
    colors = [P.S1, P.S2, "#1baf7a", "#eda100"]          # validated categorical slots 1-4
    if corrupt:
        order = ["all_sensors"] + list(runs[names[0]]["test"]["corruptions"])
        get = lambda n, s: (runs[n]["test"]["scenarios"][s] if s == "all_sensors"            # noqa: E731
                            else runs[n]["test"]["corruptions"][s])["all"]["accuracy"]
    else:
        order = list(SCEN_ORDER)
        get = lambda n, s: runs[n]["test"]["scenarios"][s]["all"]["accuracy"]                # noqa: E731
    x = np.arange(len(order))
    w = 0.8 / max(len(names), 1)
    fig, ax = plt.subplots(figsize=(9, 4.4))
    for k, n in enumerate(names[:4]):
        vals = [get(n, s) for s in order]
        xs = x - 0.4 + w / 2 + k * w
        ax.bar(xs, vals, w * 0.9, color=colors[k], label=_short(n) + (" (final)" if k == 0 else ""))
        for xi, v in zip(xs, vals):
            ax.text(xi, v + 0.01, f"{v:.2f}", ha="center", color=P.INK2, fontsize=6.5, rotation=90)
    ax.set_xticks(x, [s.replace("_", "\n").replace("all\nsensors", "clean" if corrupt else "all\nsensors") for s in order])
    ax.set_ylim(0, 1.05)
    ax.grid(axis="x", visible=False)
    ax.set_ylabel("Test accuracy")
    ax.set_title("Accuracy with silently corrupted sensors: final model vs ablations" if corrupt
                 else "Accuracy with missing sensors: final model vs ablations")
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.2), ncol=4, fontsize=8)
    P._save(fig, path)


def _seed_section(runs: dict[str, Any], rows: dict[str, dict[str, float]], sel: str, seed_runs: list[str]) -> list[str]:
    """Mean ± std over training seeds (seed 42 = the main run) for the final model and seeded ablations."""
    groups: dict[str, list[str]] = {}
    for n in seed_runs:
        base = n.rsplit("__seed", 1)[0]
        groups.setdefault(base, [base] if base in runs else []).append(n)
    keys = [("val_macro_f1", "val mF1"), ("test_acc", "test acc"), ("test_macro_f1", "test mF1"),
            ("one_missing_acc", "acc, 1 sensor missing")]
    md = ["## 3c. Run-to-run noise: mean ± std over 3 training seeds (42, 1, 2; same site split)", "",
          "| run | n seeds | " + " | ".join(k[1] for k in keys) + " | mean acc under corruption |",
          "|---|---|" + "---|" * (len(keys) + 1)]
    for base, members in groups.items():
        cells = []
        for k, _ in keys:
            v = np.array([rows[m][k] for m in members])
            cells.append(f"{v.mean():.3f} ± {v.std(ddof=1) if len(v) > 1 else 0:.3f}")
        corr = np.array([np.mean([c["all"]["accuracy"] for c in runs[m]["test"]["corruptions"].values()])
                         for m in members if "corruptions" in runs[m]["test"]])
        cstr = f"{corr.mean():.3f} ± {corr.std(ddof=1) if len(corr) > 1 else 0:.3f}" if len(corr) else "–"
        label = "final (" + sel + ")" if base == sel else base.split("__", 1)[1]
        md.append(f"| {label} | {len(members)} | " + " | ".join(cells) + f" | {cstr} |")
    md.append("")
    return md
